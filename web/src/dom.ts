/** Tiny DOM helpers: h() builds elements, icon() inlines the SVG icons used across the app. */
export type Child = Node | string | number | null | undefined | false | Child[]

export function h(tag: string, props?: Record<string, any> | null, ...kids: Child[]): HTMLElement {
  const el = document.createElement(tag)
  if (props) {
    for (const k of Object.keys(props)) {
      const v = props[k]
      if (v == null || v === false) continue
      if (k === 'class') el.className = v
      else if (k === 'f') el.setAttribute('data-f', v === true ? '' : String(v))
      else if (k === 'style' && typeof v === 'object') Object.assign(el.style, v)
      else if (k.slice(0, 2) === 'on') el.addEventListener(k.slice(2), v)
      else if (k === 'html') el.innerHTML = v
      else el.setAttribute(k, v === true ? '' : String(v))
    }
  }
  const add = (c: Child) => {
    if (c == null || c === false) return
    if (Array.isArray(c)) c.forEach(add)
    else el.appendChild(typeof c === 'object' ? c : document.createTextNode(String(c)))
  }
  kids.forEach(add)
  return el
}

